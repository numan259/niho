test('external VTT captions load into the overlay and Off removes them', async ({ page }) => {
  await page.route('**/fixture.vtt', route => route.fulfill({ contentType: 'text/vtt', body: 'WEBVTT\n\n00:00.000 --> 59:59.000\nExternal subtitle test\n' }))
  await page.route('**/fixture.mp4', route => route.fulfill({ status: 204 }))
  await page.goto('/e2e/player.html?external')
  await expect(page.locator('.player__captions')).toContainText('External subtitle test')
  await expect(page.locator('.player__captions')).toBeVisible()
  await page.getByRole('button', { name: 'Audio and subtitles', exact: true }).click()
  await expect(page.getByRole('button', {name: 'External English', exact: true})).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Off', exact: true }).click()
  await expect(page.locator('video track')).toHaveCount(0)
  await expect(page.locator('.player__captions')).not.toBeVisible()
})

test('grouped servers keep every alternative and language lists fit portrait and landscape', async ({ page }) => {
  await page.route('**/fixture.mp4*', route => route.fulfill({status: 204}))
  await page.route('**/fixture.vtt*', route => route.fulfill({contentType: 'text/vtt', body: 'WEBVTT\n\n00:00.000 --> 59:59.000\nCaption\n'}))
  await page.goto('/e2e/player.html?grouped')
  await page.getByRole('button', {name: 'Change server', exact: true}).click()
  const servers = page.getByRole('dialog', {name: 'Change server'})
  await expect(servers.locator('.player__server-heading')).toHaveCount(2)
  await servers.getByRole('button', {name: /VidNest/}).click()
  await expect(servers.locator('.player__server-options button')).toHaveCount(5)
  await page.screenshot({path: 'test-results/servers-grouped.png'})
  await servers.getByRole('button', {name: /^Server 4 /}).click()
  await expect(page.locator('video')).toHaveAttribute('src', '/fixture.mp4?server=3')
  for (const size of [{width: 393, height: 851}, {width: 915, height: 412}, {width: 1440, height: 900}]) {
    await page.setViewportSize(size)
    await page.getByRole('button', {name: 'Audio and subtitles'}).click()
    const panel = page.getByRole('dialog', {name: 'Audio & subtitles'})
    await expect(panel).toBeInViewport()
    const box = (await panel.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.y + box.height).toBeLessThanOrEqual(size.height)
    const list = panel.getByRole('region', {name: 'Subtitle tracks'})
    await expect(list.getByRole('button')).toHaveCount(26)
    await list.getByRole('button', {name: 'Turkish', exact: true}).click()
    await expect(list.getByRole('button', {name: 'Turkish', exact: true})).toHaveAttribute('aria-pressed', 'true')
    await list.getByRole('button', {name: 'Subtitle alternative 25', exact: true}).scrollIntoViewIfNeeded()
    await expect(list.getByRole('button', {name: 'Subtitle alternative 25', exact: true})).toBeInViewport()
    await list.getByRole('button', {name: 'Turkish', exact: true}).scrollIntoViewIfNeeded()
    await page.screenshot({path: `test-results/languages-${size.width}.png`})
    await page.getByRole('button', {name: 'Close panel'}).click()
  }
})
